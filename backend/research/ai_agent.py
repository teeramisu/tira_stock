    def _check_novelty(self, h: FactorHypothesis) -> float:
        """Check if hypothesis is novel (not in existing catalog)."""
        try:
            from factors.catalog import FACTOR_CATALOG  # type: ignore
            existing_names = {f.name.lower() for f in FACTOR_CATALOG.values()} if FACTOR_CATALOG else set()
        except Exception:
            existing_names = set()
        if h.name.lower() in existing_names:
            return 0.2  # Low novelty
        # Check for keyword overlap
        h_words = set(h.name.lower().split())
        max_overlap = 0
        for name in existing_names:
            overlap = len(h_words & set(name.split()))
            max_overlap = max(max_overlap, overlap)
        if max_overlap >= 2:
            return 0.5
        return 0.8

    def _check_implementability(self, h: FactorHypothesis) -> float:
        """Check if hypothesis can be implemented with available data."""
        # Check if implementation code is provided
        if h.implementation_code and len(h.implementation_code) > 20:
            return 0.8
        # Check if formula is clear
        if h.formula and len(h.formula) > 10:
            return 0.7
        return 0.4

    def _check_rationale(self, h: FactorHypothesis) -> float:
        """Check if economic rationale makes sense."""
        if not h.rationale or len(h.rationale) < 10:
            return 0.3
        # Check for common academic keywords
        academic_keywords = [
            "动量", "价值", "反转", "波动", "流动性", "情绪",
            "信息", "风险", "溢价", "均值回归", "行为金融",
        ]
        score = 0.5
        for kw in academic_keywords:
            if kw in h.rationale:
                score += 0.05
        return min(1.0, score)

    def _check_regime_alignment(self, h: FactorHypothesis) -> float:
        """Check if hypothesis is aligned with expected regimes."""
        if not h.expected_regime:
            return 0.5
        # More specific regime targeting = higher score
        if len(h.expected_regime) == 1:
            return 0.8
        elif len(h.expected_regime) == 2:
            return 0.6
        return 0.4

    def _score_to_recommendation(self, score: float) -> str:
        """Convert overall score to recommendation."""
        if score >= 0.75:
            return "强烈推荐: 立即回测验证"
        elif score >= 0.60:
            return "推荐: 值得回测"
        elif score >= 0.40:
            return "一般: 需改进后回测"
        return "不推荐: 需要重新设计"

    def _generate_insights(
        self, hypotheses: list[FactorHypothesis], regime: str
    ) -> list[str]:
        """Generate insights from hypothesis generation."""
        insights = []
        sources = {}
        for h in hypotheses:
            sources[h.source] = sources.get(h.source, 0) + 1

        insights.append(f"共生成 {len(hypotheses)} 个因子假设")

        llm_count = sources.get("llm", 0)
        if llm_count:
            insights.append(f"其中 LLM 生成 {llm_count} 个，规则生成 {len(hypotheses) - llm_count} 个")

        # Regime-specific insight
        regime_specific = [h for h in hypotheses if regime in h.expected_regime]
        insights.append(f"适配当前 {regime} 状态的因子: {len(regime_specific)} 个")

        return insights

    def _generate_recommendations(
        self, promising: list[str], rejected: list[str], regime: str
    ) -> list[str]:
        """Generate action recommendations."""
        recs = []
        if promising:
            recs.append(f"有 {len(promising)} 个因子值得回测: {', '.join(promising[:3])}")
        if rejected:
            recs.append(f"有 {len(rejected)} 个因子不推荐，原因: 新颖性不足或实现困难")
        if not promising:
            recs.append("当前无特别有价值的因子假设，建议等待更多市场数据")
        return recs

    def _load_existing(self) -> None:
        """Load existing hypotheses from disk."""
        path = RESEARCH_LOG_DIR / "hypotheses.json"
        if not path.exists():
            return
        try:
            data = json.loads(path.read_text(encoding="utf-8"))
            for item in data:
                self._hypotheses.append(FactorHypothesis(**item))
        except Exception:
            pass

    def _save_hypotheses(self, hypotheses: list[FactorHypothesis]) -> None:
        """Save hypotheses to disk."""
        RESEARCH_LOG_DIR.mkdir(parents=True, exist_ok=True)
        path = RESEARCH_LOG_DIR / "hypotheses.json"

        existing = []
        if path.exists():
            try:
                existing = json.loads(path.read_text(encoding="utf-8"))
            except Exception:
                pass

        new_entries = [
            {
                "hypothesis_id": h.hypothesis_id,
                "name": h.name,
                "description": h.description,
                "rationale": h.rationale,
                "formula": h.formula,
                "expected_regime": h.expected_regime,
                "risk_factors": h.risk_factors,
                "implementation_code": h.implementation_code,
                "confidence": h.confidence,
                "source": h.source,
                "evaluated": h.evaluated,
                "eval_result": h.eval_result,
                "created_at": h.created_at,
            }
            for h in hypotheses
        ]
        existing.extend(new_entries)

        # Keep last 200
        existing = existing[-200:]
        path.write_text(json.dumps(existing, ensure_ascii=False, indent=2), encoding="utf-8")

    def _save_report(self, report: ResearchReport) -> None:
        """Save research report to disk."""
        RESEARCH_LOG_DIR.mkdir(parents=True, exist_ok=True)
        path = RESEARCH_LOG_DIR / f"report_{report.report_date}.json"

        data = {
            "report_date": report.report_date,
            "market": report.market,
            "regime": report.regime,
            "hypotheses_generated": report.hypotheses_generated,
            "hypotheses_evaluated": report.hypotheses_evaluated,
            "promising_factors": report.promising_factors,
            "rejected_factors": report.rejected_factors,
            "insights": report.insights,
            "recommendations": report.recommendations,
        }
        path.write_text(json.dumps(data, ensure_ascii=False, indent=2), encoding="utf-8")
