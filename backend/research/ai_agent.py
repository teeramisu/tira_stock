"""AI Research Agent: LLM-powered factor mining and hypothesis generation.

This module uses an LLM (or offline rule-based fallback) to:
1. Generate new factor hypotheses based on market observations
2. Evaluate factor ideas against existing catalog
3. Produce backtest-ready factor code snippets
4. Auto-generate research reports

Usage:
    from research.ai_agent import AIResearchAgent
    agent = AIResearchAgent()
    hypotheses = agent.generate_hypotheses(regime="BEAR", market="cn")
    result = agent.evaluate_hypothesis(hypothesis)
"""

from __future__ import annotations

import json
import logging
from dataclasses import dataclass, field
from datetime import date, datetime
from pathlib import Path
from typing import Any

import numpy as np

logger = logging.getLogger(__name__)

RESEARCH_LOG_DIR = Path(__file__).resolve().parents[2] / "data" / "ai_research"


@dataclass
class FactorHypothesis:
    """A factor hypothesis generated by the AI agent."""

    hypothesis_id: str
    name: str
    description: str
    rationale: str  # economic rationale
    formula: str  # mathematical formula (pseudo-code)
    expected_regime: list[str]  # regimes where this factor should work
    risk_factors: list[str]  # potential failure modes
    implementation_code: str  # Python code snippet
    confidence: float = 0.5  # 0-1 confidence score
    source: str = "rule_based"  # "llm" or "rule_based"
    evaluated: bool = False
    eval_result: dict[str, Any] = field(default_factory=dict)
    created_at: str = ""


@dataclass
class ResearchReport:
    """AI-generated research report."""

    report_date: str
    market: str
    regime: str
    hypotheses_generated: int
    hypotheses_evaluated: int
    promising_factors: list[str]
    rejected_factors: list[str]
    insights: list[str]
    recommendations: list[str]


class AIResearchAgent:
    """AI-powered research agent for factor mining.

    Supports two modes:
    1. LLM mode: Uses OpenAI/local LLM API for creative hypothesis generation
    2. Rule-based mode: Uses pre-defined templates and market observations
    """

    def __init__(self, *, use_llm: bool = False):
        self.use_llm = use_llm
        self._hypotheses: list[FactorHypothesis] = []
        self._load_existing()

    def generate_hypotheses(
        self,
        *,
        regime: str = "UNKNOWN",
        market: str = "cn",
        n_hypotheses: int = 5,
        focus_area: str = "",
    ) -> list[FactorHypothesis]:
        """Generate factor hypotheses based on current market conditions.

        Args:
            regime: Current market regime.
            market: Market code.
            n_hypotheses: Number of hypotheses to generate.
            focus_area: Optional focus (e.g., "momentum", "value", "volatility").

        Returns:
            List of FactorHypothesis objects.
        """
        if self.use_llm and self.llm_api_key:
            return self._generate_with_llm(
                regime=regime, market=market, n=n_hypotheses, focus=focus_area
            )
        return self._generate_rule_based(
            regime=regime, market=market, n=n_hypotheses, focus=focus_area
        )

    def evaluate_hypothesis(
        self, hypothesis: FactorHypothesis
    ) -> dict[str, Any]:
        """Evaluate a factor hypothesis.

        Checks:
        1. Novelty: Is this different from existing factors?
        2. Implementability: Can this be coded with available data?
        3. Economic rationale: Does it make economic sense?
        4. Regime alignment: Is it suited for current regime?

        Returns:
            Evaluation result dict.
        """
        result: dict[str, Any] = {
            "hypothesis_id": hypothesis.hypothesis_id,
            "novelty_score": self._check_novelty(hypothesis),
            "implementability": self._check_implementability(hypothesis),
            "rationale_score": self._check_rationale(hypothesis),
            "regime_alignment": self._check_regime_alignment(hypothesis),
        }

        # Overall score
        scores = [
            result["novelty_score"],
            result["implementability"],
            result["rationale_score"],
            result["regime_alignment"],
        ]
        result["overall_score"] = float(np.mean(scores))
        result["recommendation"] = self._score_to_recommendation(result["overall_score"])

        hypothesis.evaluated = True
        hypothesis.eval_result = result
        return result

    def backtest_hypothesis(
        self, hypothesis: FactorHypothesis, *, market: str = "cn"
    ) -> dict[str, Any]:
        """Run quantitative backtest on a hypothesis using FactorBacktestEngine.

        Links hypothesis name to known factor in FACTOR_CATALOG, then
        runs full IC / rank IC / quantile analysis.
        Returns dict with backtest results or error info.
        """
        try:
            from factors.backtest import FactorBacktestEngine
            from factors.catalog import FACTOR_CATALOG

            # Try to match hypothesis name to a known factor spec
            matched = None
            h_name = hypothesis.name.lower().replace(" ", "_")
            for spec in FACTOR_CATALOG:
                if h_name in spec.name.lower().replace(" ", "_"):
                    matched = spec
                    break
                if h_name in spec.description.lower()[:50]:
                    matched = spec
                    break

            if matched is None:
                return {"status": "skipped", "reason": f"no catalog match for '{hypothesis.name}'"}

            engine = FactorBacktestEngine(market=market)
            engine.load_data()
            factor_df = engine.compute_factor(matched)
            if factor_df is not None:
                engine.factor_values[matched.name] = factor_df

            fwd = 5
            result = engine.evaluate_factor(matched.name, forward_period=fwd)
            if result:
                bt_result = {
                    "status": "completed",
                    "factor_name": matched.name,
                    "ic_mean": float(result.get("ic", 0)),
                    "rank_ic_mean": float(result.get("rank_ic", 0)),
                    "ic_std": float(result.get("ic_std", 0)),
                    "rank_ic_std": float(result.get("rank_ic_std", 0)),
                    "ic_ir": float(result.get("ic_ir", 0)),
                    "rank_ic_ir": float(result.get("rank_ic_ir", 0)),
                    "spread": float(result.get("spread", 0)),
                    "forward_period": fwd,
                }
                hypothesis.eval_result["backtest"] = bt_result
                return bt_result
        except Exception as e:
            logger.debug("Factor backtest failed for %s: %s", hypothesis.name, e)
            return {"status": "failed", "error": str(e)}
        return {"status": "skipped", "reason": "unknown"}

    def run_full_research_cycle(
        self,
        *,
        regime: str = "UNKNOWN",
        market: str = "cn",
        n_hypotheses: int = 5,
        run_backtest: bool = True,
    ) -> ResearchReport:
        """Run a complete research cycle: generate → evaluate → backtest → report.

        Args:
            regime: Current market regime.
            market: Market code.
            n_hypotheses: Number of hypotheses to generate.
            run_backtest: Whether to auto-backtest promising hypotheses.

        Returns:
            ResearchReport with findings.
        """
        logger.info("Starting AI research cycle: regime=%s, market=%s", regime, market)

        # Generate hypotheses
        hypotheses = self.generate_hypotheses(
            regime=regime, market=market, n_hypotheses=n_hypotheses
        )

        # Evaluate each
        promising = []
        rejected = []
        for h in hypotheses:
            result = self.evaluate_hypothesis(h)
            if result["overall_score"] >= 0.6:
                promising.append(h.name)
            else:
                rejected.append(h.name)

        # Auto-backtest promising hypotheses
        backtested_ok = []
        if run_backtest:
            for h in hypotheses:
                if h.name in promising:
                    bt = self.backtest_hypothesis(h, market=market)
                    if bt.get("status") == "completed":
                        backtested_ok.append(h.name)
                        ic = bt.get("rank_ic_mean", 0)
                        if abs(ic) > 0.02:
                            logger.info("Factor %s rank IC=%.4f (actionable)", h.name, ic)

        # Save hypotheses (with backtest results embedded)
        self._save_hypotheses(hypotheses)

        # Generate insights
        insights = self._generate_insights(hypotheses, regime)
        recommendations = self._generate_recommendations(promising, rejected, regime)
        if backtested_ok:
            recommendations.append(f"已自动回测 {len(backtested_ok)} 个因子")

        report = ResearchReport(
            report_date=date.today().isoformat(),
            market=market,
            regime=regime,
            hypotheses_generated=len(hypotheses),
            hypotheses_evaluated=len(hypotheses),
            promising_factors=promising,
            rejected_factors=rejected,
            insights=insights,
            recommendations=recommendations,
        )

        # Save report
        self._save_report(report)

        logger.info(
            "Research cycle complete: %d generated, %d promising",
            len(hypotheses),
            len(promising),
        )
        return report

    def _generate_rule_based(
        self,
        *,
        regime: str,
        market: str,
        n: int,
        focus: str,
    ) -> list[FactorHypothesis]:
        """Generate hypotheses using rule-based templates."""
        templates = self._get_regime_templates(regime, market)

        if focus:
            templates = [t for t in templates if focus.lower() in t.get("tags", [])]

        hypotheses = []
        now = datetime.now().isoformat()

        for i, tmpl in enumerate(templates[:n]):
            h = FactorHypothesis(
                hypothesis_id=f"rh_{date.today().isoformat()}_{i:03d}",
                name=tmpl["name"],
                description=tmpl["description"],
                rationale=tmpl["rationale"],
                formula=tmpl["formula"],
                expected_regime=tmpl.get("regimes", [regime]),
                risk_factors=tmpl.get("risks", ["数据不足", "过拟合"]),
                implementation_code=tmpl.get("code", "# Implementation TBD"),
                confidence=tmpl.get("confidence", 0.5),
                source="rule_based",
                created_at=now,
            )
            hypotheses.append(h)

        return hypotheses

    def _generate_with_llm(
        self,
        *,
        regime: str,
        market: str,
        n: int,
        focus: str,
    ) -> list[FactorHypothesis]:
        """Generate hypotheses using DeepSeek API (via the unified LLM client).

        Requires DEEPSEEK_API_KEY in .env. Falls back to rule-based when unavailable.
        """
        from services.llm_client import is_api_available, chat_completion

        if not is_api_available():
            logger.warning("DEEPSEEK_API_KEY not configured, falling back to rule-based")
            return self._generate_rule_based(regime=regime, market=market, n=n, focus=focus)

        try:
            prompt = self._build_llm_prompt(regime, market, n, focus)
            system = "你是一个量化研究助手，专注于A股市场因子挖掘。以JSON数组格式返回。"
            content = chat_completion(prompt, max_tokens=2000, system=system)
            if not content:
                return self._generate_rule_based(regime=regime, market=market, n=n, focus=focus)
            return self._parse_llm_response(content, regime)

        except Exception as e:
            logger.warning("DeepSeek generation failed: %s, falling back to rule-based", e)
            return self._generate_rule_based(regime=regime, market=market, n=n, focus=focus)

    def _build_llm_prompt(self, regime: str, market: str, n: int, focus: str) -> str:
        """Build prompt for LLM factor generation."""
        focus_str = f"重点关注{focus}类因子。" if focus else ""
        return f"""当前市场状态: {regime}
市场: {market} (A股)
{focus_str}

请生成{n}个新的量化因子假设，每个包含:
1. 因子名称（简洁中文）
2. 描述（一句话）
3. 经济学逻辑（为什么有效）
4. 计算公式（伪代码）
5. 适用市场状态
6. 潜在风险
7. Python实现代码片段

请以JSON数组格式返回，每个元素包含上述字段。"""

    def _parse_llm_response(self, content: str, regime: str) -> list[FactorHypothesis]:
        """Parse LLM response into FactorHypothesis objects."""
        # Try to extract JSON from response
        try:
            # Find JSON array in content
            start = content.find("[")
            end = content.rfind("]") + 1
            if start >= 0 and end > start:
                items = json.loads(content[start:end])
            else:
                items = json.loads(content)
        except json.JSONDecodeError:
            logger.warning("Failed to parse LLM response as JSON")
            return []

        hypotheses = []
        now = datetime.now().isoformat()

        for i, item in enumerate(items):
            h = FactorHypothesis(
                hypothesis_id=f"llm_{date.today().isoformat()}_{i:03d}",
                name=item.get("name", f"LLM因子_{i+1}"),
                description=item.get("description", ""),
                rationale=item.get("rationale", ""),
                formula=item.get("formula", ""),
                expected_regime=item.get("regimes", [regime]),
                risk_factors=item.get("risks", []),
                implementation_code=item.get("code", ""),
                confidence=0.6,
                source="llm",
                created_at=now,
            )
            hypotheses.append(h)

        return hypotheses

